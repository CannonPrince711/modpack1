#!/usr/bin/env python3
"""Generate the Odyssey Quartermaster shop (overrides/kubejs/server_scripts/shop.js).

The Quartermaster is a stationary villager spawned once at world spawn. He sells the same curated, tiered gear that
tools/gen_gear_loot.py puts in loot, for Lightman's Currency coins that bosses drop (see progression.js).

Prices use one coin type each, so they do not depend on the coin exchange rate:
  tier 1 (iron-class)       4 gold coins            a first overworld boss pays 5 gold
  tier 2 (diamond-class)    3 emerald coins         a Nether boss pays 3 emerald
  tier 3 (netherite-class)  8 emerald coins         an End boss pays 8 emerald
  mythic extras             2 diamond coins
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "overrides" / "kubejs" / "server_scripts" / "shop.js"

COIN = "lightmanscurrency:coin_"
TIER_PRICE = {"overworld": (COIN + "gold", 4), "nether": (COIN + "emerald", 3), "end": (COIN + "emerald", 8)}
MYTHIC_PRICE = (COIN + "diamond", 2)
# (item, count sold, price coin, price count)
SUPPLIES = [
    ("minecraft:golden_apple", 1, COIN + "gold", 2),
    ("minecraft:ender_pearl", 1, COIN + "gold", 1),
    ("minecraft:experience_bottle", 8, COIN + "gold", 1),
    ("minecraft:totem_of_undying", 1, COIN + "emerald", 4),
    ("lightmanscurrency:wallet_leather", 1, COIN + "gold", 1),
]


def load_loot_tool():
    spec = importlib.util.spec_from_file_location("gen_gear_loot", ROOT / "tools" / "gen_gear_loot.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def trades():
    loot = load_loot_tool()
    rows = []
    for tier, items in loot.GEAR.items():
        coin, count = TIER_PRICE[tier]
        rows += [(item, 1, coin, count) for item in items]
    rows += [(item, 1, MYTHIC_PRICE[0], MYTHIC_PRICE[1]) for item in loot.MYTHIC]
    return rows + SUPPLIES


def render():
    rows = trades()
    lines = [
        "// Generated by tools/gen_shop.py. Do not edit by hand.",
        "// The Odyssey Quartermaster: a stationary villager at world spawn that sells tiered gear for boss coins.",
        "// Each row: [item sold, count sold, coin paid, coins paid].",
        "const SHOP_TRADES = [",
        *[f"  {json.dumps(list(row))}," for row in rows],
        "]",
        "",
        "function shopOffers() {",
        "  return SHOP_TRADES.map(row => ({",
        "    buy: { id: row[2], Count: row[3] },",
        "    sell: { id: row[0], Count: row[1] },",
        "    maxUses: 9999, uses: 0, rewardExp: false, xp: 0, demand: 0, specialPrice: 0, priceMultiplier: 0",
        "  }))",
        "}",
        "",
        "function spawnQuartermaster(server) {",
        "  const level = server.overworld()",
        "  const spawn = level.getSharedSpawnPos()",
        "  const npc = level.createEntity(\"minecraft:villager\")",
        "  npc.setPosition(spawn.x + 0.5, spawn.y, spawn.z + 0.5)",
        "  npc.addTag(\"ddo_quartermaster\")",
        "  npc.mergeNbt({",
        "    NoAI: true, Invulnerable: true, PersistenceRequired: true, Silent: true,",
        "    CustomName: JSON.stringify({ text: \"Odyssey Quartermaster\", color: \"gold\", italic: false }),",
        "    CustomNameVisible: true,",
        "    VillagerData: { profession: \"minecraft:weaponsmith\", level: 5, type: \"minecraft:plains\" },",
        "    Offers: { Recipes: shopOffers() }",
        "  })",
        "  npc.spawn()",
        "  const data = server.persistentData",
        "  data.putInt(\"ddo_shop_x\", spawn.x)",
        "  data.putInt(\"ddo_shop_y\", spawn.y)",
        "  data.putInt(\"ddo_shop_z\", spawn.z)",
        "  data.putBoolean(\"ddo_shop_spawned\", true)",
        "  console.info(`shop: Quartermaster spawned at ${spawn.x} ${spawn.y} ${spawn.z} with ${SHOP_TRADES.length} trades`)",
        "}",
        "",
        "// Spawn him once, a few seconds after the world loads (spawn chunks must be ready).",
        "ServerEvents.tick(event => {",
        "  const server = event.server",
        "  if (server.tickCount < 100 || server.persistentData.getBoolean(\"ddo_shop_spawned\")) return",
        "  spawnQuartermaster(server)",
        "})",
        "",
        "// !shop tells players where he is; an operator can run it to bring him back if he is ever lost.",
        "PlayerEvents.chat(event => {",
        "  if (event.message.trim().toLowerCase() !== \"!shop\") return",
        "  event.cancel()",
        "  const data = event.server.persistentData",
        "  if (!data.getBoolean(\"ddo_shop_spawned\")) {",
        "    event.player.tell(\"The Quartermaster has not arrived yet.\")",
        "    return",
        "  }",
        "  event.player.tell(`The Odyssey Quartermaster stands at ${data.getInt(\"ddo_shop_x\")} ${data.getInt(\"ddo_shop_y\")} ${data.getInt(\"ddo_shop_z\")}. Bring boss coins.`)",
        "})",
        "",
    ]
    return "\n".join(lines)


def main():
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(trades())} trades")


if __name__ == "__main__":
    main()
